import { test, expect } from '@playwright/test';

test('add and adjust dishes in one menu surface', async ({ page }, info) => {
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: /Plan a new cook/ }).click();
  await page.getByRole('button',{name:'Start with a template',exact:true}).click();
  await page.getByRole('button', { name: 'Add smoked brisket' }).click();
  const menu = page.getByRole('region', { name: 'Cook overview' });
  const brisket = menu.getByRole('article', { name: 'Smoked brisket', exact: true });
  await expect(brisket.getByRole('region', { name: 'Smoked brisket steps' })).toBeVisible();
  await expect(brisket.getByRole('button', { name: 'Edit Smoked brisket', exact: true })).toBeFocused();
  await expect(page.getByText('Back to menu', { exact: false })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Dish details' })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Choose a template' })).toHaveCount(0);
  await expect(brisket.getByLabel('Dish name')).not.toBeVisible();
  await page.getByRole('button', { name: '+ Add a dish', exact: true }).click();
  await expect(menu.getByRole('region', { name: 'Add dish' })).toBeVisible();
  await page.getByRole('button', { name: 'Cancel adding', exact: true }).click();
  await expect(menu.locator('.workspace-dish')).toHaveCount(1);
  await page.getByRole('button', { name: '+ Add a dish', exact: true }).click();
  await page.getByRole('button', { name: 'Add grilled beer-bath brats' }).click();
  const brats = menu.getByRole('article', { name: 'Grilled beer-bath brats', exact: true });
  await expect(brats.getByRole('region', { name: 'Grilled beer-bath brats steps' })).toBeVisible();
  await expect(brisket.getByRole('region', { name: 'Smoked brisket steps' })).toHaveCount(0);
  await brisket.getByRole('button', { name: 'Edit Smoked brisket', exact: true }).click();
  await expect(brats.getByRole('region', { name: 'Grilled beer-bath brats steps' })).toHaveCount(0);
  await brisket.getByText('Dish settings', { exact: true }).click();
  await brisket.getByLabel('Dish name', { exact: true }).fill('Sunday brisket');
  const renamed = menu.getByRole('article', { name: 'Sunday brisket', exact: true });
  await renamed.getByText('Dish settings', { exact: true }).click();
  await menu.evaluate(element => element.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: info.outputPath('flat-menu-viewport.png'), fullPage: false });
  await page.screenshot({ path: info.outputPath('flat-menu.png'), fullPage: true });
  await info.attach('flat-menu.png', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
  await renamed.getByRole('button', { name: 'Edit Sunday brisket', exact: true }).click();
  await expect(renamed.getByRole('region', { name: 'Sunday brisket steps' })).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});
