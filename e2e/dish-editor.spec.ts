import { test, expect } from '@playwright/test';
import { newMeal, createDish } from '../src/domain/meal';
import { cookTimeline, recordEvent } from '../src/domain/cookState';
test('dish editor separates adding from selecting and preserves cooks', async ({ page }, info) => {
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: /Plan a new cook/ }).click();
  await page.getByRole('button', { name: 'Add smoked brisket' }).click();
  await expect(page.getByRole('heading', { name: 'Choose a template' })).toHaveCount(0);
  await page.getByRole('button', { name: '+ Add a dish', exact: true }).click();
  await page.getByRole('button', { name: 'Add grilled beer-bath brats' }).click();
  await page.getByRole('button', { name: 'Edit Smoked brisket', exact: true }).click();
  const editor = page.getByRole('region', { name: 'Dish editor' });
  await expect(editor.getByRole('region', { name: 'Smoked brisket steps' })).toBeVisible();
  await editor.getByText('Dish settings', { exact: true }).click();
  await editor.getByLabel('Dish name').fill('Saturday brisket');
  await editor.getByText('Dish settings', { exact: true }).click();
  await editor.getByRole('button', { name: 'Add a step to Saturday brisket' }).click();
  await editor.getByLabel('Step title', { exact: true }).fill('Get wood pellets');
  await editor.getByRole('button', { name: 'Save step' }).click();
  await expect(editor.getByText('Get wood pellets')).toBeVisible();
  await editor.getByText('Dish settings', { exact: true }).click();
  await editor.getByLabel('Equipment', { exact: true }).fill('Patio smoker');
  await editor.getByText('Dish settings', { exact: true }).click();
  await editor.scrollIntoViewIfNeeded();
  await info.attach('dish-editor.png', { body: await page.screenshot({ fullPage: false }), contentType: 'image/png' });
  await page.screenshot({ path: info.outputPath('dish-editor.png'), fullPage: false });
  await page.getByRole('button', { name: 'Edit Saturday brisket', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await page.getByRole('button', { name: 'Edit Grilled beer-bath brats', exact: true }).click();
  await expect(page.getByText('Get wood pellets', { exact: true })).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: /Resume planning/ }).click();
  await page.getByRole('button', { name: 'Edit Saturday brisket', exact: true }).click();
  await expect(page.getByText('Get wood pellets', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});

test('existing cooking events and IDs survive contextual step changes', async ({ page }) => {
  let meal = { ...newMeal(), dishes: [createDish('brisket'), createDish('brats')], mode: 'cooking' as const };
  const tasks = cookTimeline(meal);
  const first = tasks[0];
  const saved = recordEvent(recordEvent(meal, first.id, 'completed', '2026-10-25T12:00:00.000Z'), first.id, 'temperature', '2026-10-25T12:01:00.000Z', 165, '°F');
  await page.goto('/');
  await page.evaluate(value => localStorage.setItem('how-many-beers:meal:v1', JSON.stringify(value)), saved);
  await page.reload();
  await page.getByRole('button', { name: /View cook/ }).click();
  await page.getByRole('button', { name: 'Edit Smoked brisket', exact: true }).click();
  const region = page.getByRole('region', { name: 'Smoked brisket steps' });
  const row = region.getByRole('article', { name: first.title, exact: true });
  await row.getByRole('button', { name: 'Edit', exact: true }).click();
  await row.getByLabel('Task name').fill('Season carefully');
  await row.getByLabel('Instructions').fill('Keep the original recorded temperatures.');
  await row.getByRole('button', { name: 'Save & Close' }).click();
  await region.getByRole('button', { name: 'Move Season carefully down' }).click();
  page.once('dialog', dialog => dialog.accept());
  await region.getByRole('article', { name: 'Season carefully', exact: true }).getByRole('button', { name: 'Remove', exact: true }).click();
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!));
  expect(after.mode).toBe('cooking');
  expect(after.completed).toEqual(saved.completed);
  expect(after.events.slice(0, saved.events!.length)).toEqual(saved.events);
  expect(after.hiddenTaskIds).toContain(first.id);
  expect(after.taskOverrides[first.id].title).toBe('Season carefully');
  expect(after.dishes[1]).toEqual(saved.dishes[1]);
  await page.reload();
  await page.getByRole('button', { name: /Continue cooking/ }).click();
  await expect(page.getByText("Today's checklist")).toBeVisible();
});
