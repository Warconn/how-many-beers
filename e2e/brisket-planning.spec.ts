import { test, expect } from '@playwright/test';
import { createDish, newMeal } from '../src/domain/meal';
import { cookTimeline, recordEvent, type ExtendedMeal } from '../src/domain/cookState';
test.use({ timezoneId: 'America/New_York' });

test('brisket weight planning is explicit, updates the schedule and preserves recorded work', async ({page}, info) => {
  const dish=createDish('brisket'), brats=createDish('brats');
  let meal:ExtendedMeal={...newMeal(),serveAt:'2026-11-25T15:00',dishes:[dish,brats],mode:'cooking'};
  meal=recordEvent(meal,dish.id+':prep','completed','2026-10-25T12:00:00.000Z');
  meal.notes={[dish.id+':prep']:'Use my rub'};
  await page.goto('/');
  await page.evaluate(m=>{localStorage.clear();localStorage.setItem('how-many-beers:meal:v1',JSON.stringify(m));},meal);
  await page.reload();
  await page.getByRole('button',{name:'View cook',exact:true}).click();
  await page.getByRole('button',{name:'Edit Smoked brisket',exact:true}).click();
  const planner=page.getByRole('region',{name:'Brisket timing'});
  await expect(planner.getByLabel('Brisket weight (lb)',{exact:true})).toHaveValue('');
  await expect(planner.getByText('Weight unknown',{exact:true})).toBeVisible();
  await planner.getByLabel('Brisket weight (lb)',{exact:true}).fill('15');
  await expect(planner.getByText(/Estimated cook time:/)).toBeVisible();
  await expect(planner.getByText(/Recommended start/)).toBeVisible();
  await expect(planner.getByLabel('Cooking profile',{exact:true})).toBeHidden();
  await planner.scrollIntoViewIfNeeded();await planner.screenshot({path:info.outputPath('compact-recommendation.png')});
  await planner.getByRole('button',{name:'Use recommended timing',exact:true}).click();
  await expect(planner.getByRole('button',{name:'Timing applied',exact:true})).toBeDisabled();
  await expect(planner.getByRole('status')).toContainText('Using estimated timing');
  const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!) as ExtendedMeal);
  const first=await saved();
  await planner.locator('.timing-choice').scrollIntoViewIfNeeded();await planner.locator('.timing-choice').screenshot({path:info.outputPath('timing-choice.png')});
  expect(first.dishes[0].cookMinutes).not.toBe(780);
  expect(first.events).toEqual(meal.events);expect(first.completed).toEqual(meal.completed);expect(first.notes).toEqual(meal.notes);expect(first.dishes[1]).toEqual(brats);
  expect(cookTimeline(first).map(t=>t.id).sort()).toEqual(cookTimeline(meal).map(t=>t.id).sort());
  await planner.getByLabel('Brisket weight (lb)',{exact:true}).fill('18');
  await planner.getByRole('button',{name:'Use recommended timing',exact:true}).click();
  expect((await saved()).dishes[0].cookMinutes).toBeGreaterThan(first.dishes[0].cookMinutes);
  await planner.getByRole('button',{name:'Use manual timing',exact:true}).click();
  await expect(planner.getByRole('status')).toContainText('Using manual timing');await expect(planner.getByRole('button',{name:'Use manual timing',exact:true})).toHaveCount(0);
  const manual=(await saved()).dishes[0].cookMinutes;
  await planner.getByLabel('Brisket weight (lb)',{exact:true}).fill('13');
  expect((await saved()).dishes[0].cookMinutes).toBe(manual);
  await planner.getByText('Timing details',{exact:true}).click();
  await planner.getByLabel('Compare my 1.5 hr/lb rule').check();
  await expect(planner.getByText(/Personal comparison: 19.5 hours/)).toBeVisible();
  await planner.evaluate(el=>el.scrollIntoView({block:"start"}));
  await page.screenshot({path:info.outputPath('brisket-planning.png')});
  await page.reload();await page.getByRole('button',{name:'View cook',exact:true}).click();await page.getByRole('button',{name:'Edit Smoked brisket',exact:true}).click();
  await expect(planner.getByLabel('Brisket weight (lb)',{exact:true})).toHaveValue('13');
  expect((await saved()).events).toEqual(meal.events);
});

test('unknown or unsupported brisket inputs do not manufacture a recommendation',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:/Plan a new cook/}).click();
  await page.getByRole('button',{name:'Start with a template',exact:true}).click();
  await page.getByRole('button',{name:'Add smoked brisket',exact:true}).click();
  const planner=page.getByRole('region',{name:'Brisket timing'});
  await expect(planner.getByRole('button',{name:'Use recommended timing',exact:true})).toBeDisabled();
  await planner.getByLabel('Brisket weight (lb)',{exact:true}).fill('15');
  await planner.getByText('Timing details',{exact:true}).click();
  await planner.getByLabel('Cooking profile', {exact:true}).selectOption('traeger-225-v1');
  await expect(planner.getByText('Estimated cook time: 7.5–15 hours',{exact:true})).toBeVisible();
  await planner.getByLabel('Weight measured',{exact:true}).selectOption('untrimmed');
  await expect(planner.getByText(/Enter trimmed weight/)).toBeVisible();
  await expect(planner.getByRole('button',{name:'Use recommended timing',exact:true})).toBeDisabled();
});
