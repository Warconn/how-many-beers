import { test, expect } from '@playwright/test';
import { newMeal, createDish } from '../src/domain/meal';
import { addStep, cookTimeline, recordEvent } from '../src/domain/cookState';

test('remove is discoverable outside settings; cancel and confirm preserve the right data', async ({ page }, info) => {
  let meal = addStep({ ...newMeal(), dishes: [createDish('brisket'), createDish('brats')], mode: 'cooking' }, 'Pellet run');
  meal = { ...meal, customTasks: meal.customTasks!.map(t => ({ ...t, dishId: meal.dishes[0].id, dishName: meal.dishes[0].name })) };
  const task = cookTimeline(meal)[0];
  meal = recordEvent(meal, task.id, 'completed', '2026-10-25T12:00:00.000Z');
  meal = recordEvent(meal, task.id, 'temperature', '2026-10-25T12:01:00.000Z', 165, '°F');
  meal = recordEvent(meal, meal.customTasks![0].id, 'started', '2026-10-25T12:02:00.000Z');
  meal.notes[task.id] = 'Keep the actual record';
  await page.goto('/');
  await page.evaluate(value => { localStorage.clear(); localStorage.setItem('how-many-beers:meal:v1', JSON.stringify(value)); }, meal);
  await page.reload();
  await page.getByRole('button', { name: /View cook/ }).click();
  const menu = page.getByRole('region', { name: 'Cook overview' });
  const brisket = menu.getByRole('article', { name: 'Smoked brisket', exact: true });
  const remove = brisket.getByRole('button', { name: 'Remove Smoked brisket', exact: true });
  await expect(remove).toBeVisible();
  await expect(page.getByLabel('Dish name', { exact: true })).toHaveCount(0);
  await menu.evaluate(el => el.scrollIntoView({ block: 'start' }));
  await page.screenshot({ path: info.outputPath('remove-dish.png'), fullPage: false });
  await info.attach('remove-dish.png', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
  await page.getByRole('button', { name: 'Edit Grilled beer-bath brats', exact: true }).click();
  const before = await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!));
  page.once('dialog', async dialog => { expect(dialog.message()).toContain('Remove Smoked brisket'); await dialog.dismiss(); });
  await remove.click();
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!))).toEqual(before);
  await expect(page.getByRole('region', { name: 'Grilled beer-bath brats steps' })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await remove.click();
  await expect(brisket).toHaveCount(0);
  const after = await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!));
  expect(after.dishes).toEqual([before.dishes[1]]);
  expect(after.customTasks.some((t: { dishId: string }) => t.dishId === before.dishes[0].id)).toBe(false);
  expect(after.events).toEqual(before.events);
  expect(after.completed).toEqual(before.completed);
  expect(after.notes).toEqual(before.notes);
  expect(after.mode).toBe('cooking');
  await expect(page.getByRole('region', { name: 'Grilled beer-bath brats steps' })).toBeVisible();
  await expect(page.getByRole('complementary', { name: 'Live schedule' }).getByText('Smoked brisket', { exact: true })).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: /View cook/ }).click();
  await expect(menu.locator('.workspace-dish')).toHaveCount(1);
  expect((await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!))).events).toEqual(before.events);
});

test('remove is a separate keyboard action with a phone-sized target', async ({ page }) => {
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: /Plan a new cook/ }).click();
  await page.getByRole('button', { name: 'Add smoked brisket', exact: true }).click();
  const dish = page.getByRole('region', { name: 'Cook overview' }).getByRole('article', { name: 'Smoked brisket', exact: true });
  const select = dish.getByRole('button', { name: 'Edit Smoked brisket', exact: true });
  const remove = dish.getByRole('button', { name: 'Remove Smoked brisket', exact: true });
  await expect(remove).toBeVisible();
  const box = await remove.boundingBox();
  expect(box!.width).toBeGreaterThanOrEqual(44);
  expect(box!.height).toBeGreaterThanOrEqual(44);
  await select.focus();
  await page.keyboard.press('Tab');
  await expect(remove).toBeFocused();
  page.once('dialog', dialog => dialog.dismiss());
  await page.keyboard.press('Enter');
  await expect(select).toHaveAttribute('aria-expanded', 'true');
  await expect(dish).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});

test('removing the last dish returns focus to Add without replacing the cook', async ({ page }) => {
  await page.goto('/');
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  await page.getByRole('button', { name: /Plan a new cook/ }).click();
  await page.getByRole('button', { name: 'Add smoked brisket', exact: true }).click();
  const id = await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!).id);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Remove Smoked brisket', exact: true }).click();
  await expect(page.getByRole('button', { name: '+ Add a dish', exact: true })).toBeFocused();
  await expect(page.getByRole('heading', { name: '0 dishes in this cook' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start cooking', exact: true })).toBeDisabled();
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('how-many-beers:meal:v1')!));
  expect(state.id).toBe(id);
  expect(state.dishes).toEqual([]);
});
